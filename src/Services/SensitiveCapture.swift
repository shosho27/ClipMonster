import Cocoa

/// Skip clipboard captures that look like secrets or that come from a password manager.
enum SensitiveCapture {
    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    static let excludedBundleIDs: Set<String> = [
        "com.1password.1password",
        "com.1password.1password7",
        "com.1password.1password8",
        "com.agilebits.onepassword7",
        "com.agilebits.onepassword4",
        "com.bitwarden.desktop",
        "com.lastpass.LastPass",
        "com.dashlane.dashlanephonefinal",
        "org.keepassx.keepassxc",
        "org.keepassxc.keepassxc",
        "com.apple.Passwords",
        "com.apple.keychainaccess",
        "com.microsoft.Authenticator",
        "com.authy.authy-mac"
    ]

    static func shouldSkip(_ pasteboard: NSPasteboard, frontmostBundleID: String?) -> Bool {
        if let types = pasteboard.types {
            if types.contains(concealed) || types.contains(transient) || types.contains(autoGenerated) {
                return true
            }
        }
        if let id = frontmostBundleID, excludedBundleIDs.contains(id) {
            return true
        }
        if let text = pasteboard.string(forType: .string) {
            let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
            if trimmed.count >= 8 && trimmed.count <= 64 && !trimmed.contains(" ") && !trimmed.contains("\n") {
                let hasLetter = trimmed.rangeOfCharacter(from: .letters) != nil
                let hasNumber = trimmed.rangeOfCharacter(from: .decimalDigits) != nil
                let hasSymbol = trimmed.rangeOfCharacter(from: CharacterSet.alphanumerics.inverted) != nil
                if hasLetter && hasNumber && hasSymbol { return true }
            }
        }
        return false
    }
}
